# Writes config/gazetteer/common_words.txt: one-word place names that are also ordinary English words
# ("reading", "mobile", "hope") or first names ("austin", "eugene"). PlaceMatcher treats these as weak
# and wants more evidence before it calls a post local. Big cities (500,000+) are left off the list, since
# a capitalised "Boston" nearly always means the city.
#
# Sources: the places table, and the word lists macOS ships in /usr/share/dict (Webster's Second
# International, public domain). Rerun after the gazetteer changes much:
#   bin/rails runner script/common_place_words.rb
dict = ENV.fetch("DICT_DIR", "/usr/share/dict")
words = File.readlines(File.join(dict, "web2"), chomp: true).select { it.match?(/\A[a-z]+\z/) }.to_set
people = File.readlines(File.join(dict, "propernames"), chomp: true).map(&:downcase).to_set
BIG_CITY = 500_000
by_name = Place.pluck(:ascii_name, :population).group_by { PlaceMatcher.normalize(it.first) }
names = by_name.select { |name, rows| name.match?(/\A[a-z]+\z/) && rows.map(&:last).max < BIG_CITY }.keys.to_set
common = (names & (words | people)).sort
path = Rails.root.join("config/gazetteer/common_words.txt")
File.write(path, "# Generated by script/common_place_words.rb; do not edit by hand.\n" + common.join("\n") + "\n")
puts "#{path}: #{common.size} words"
