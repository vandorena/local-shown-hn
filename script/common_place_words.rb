# Writes config/gazetteer/common_words.txt: one-word place names that are also ordinary words. PlaceMatcher
# treats these as weak, and never matches a village or district on one. A name is common when it is:
#   - an English word or first name in the word lists macOS ships in /usr/share/dict ("reading", "hope",
#     "austin"; Webster's Second International, public domain);
#   - used in lowercase in LOWERCASE_POSTS or more Show HN posts: newer words that dictionary lacks
#     ("demo", "startup", "hours");
#   - only a village's or district's name, and used in VILLAGE_POSTS or more posts in any case ("English",
#     "FOSS"). Real villages almost never come up on HN.
# Big cities (500,000+) are left off the list, since a capitalised "Boston" nearly always means the city.
#
# It needs the places table and the posts (a full backfill). Rerun after either changes much:
#   bin/rails runner script/common_place_words.rb
dict = ENV.fetch("DICT_DIR", "/usr/share/dict")
words = File.readlines(File.join(dict, "web2"), chomp: true).select { it.match?(/\A[a-z]+\z/) }.to_set
people = File.readlines(File.join(dict, "propernames"), chomp: true).map(&:downcase).to_set
BIG_CITY = 500_000
LOWERCASE_POSTS = 3
VILLAGE_POSTS = 10

by_name = Hash.new { |h, k| h[k] = [ 0, 0 ] } # name => [biggest population, biggest town (5,000+) population]
Place.in_batches(of: 50_000) do |batch|
  batch.pluck(:ascii_name, :population, :kind).each do |ascii, pop, kind|
    name = PlaceMatcher.normalize(ascii)
    next unless name.match?(/\A[a-z]+\z/)
    sizes = by_name[name]
    sizes[0] = [ sizes[0], pop ].max
    sizes[1] = [ sizes[1], pop ].max if kind != "district" && pop >= GazetteerDownload::VILLAGE_MAX
  end
end
names = by_name.select { |_, (biggest, _)| biggest < BIG_CITY }

lower = Hash.new(0)
any = Hash.new(0)
sanitizer = Rails::HTML5::FullSanitizer.new
Post.select(:id, :title, :story_text).find_each do |post|
  seen_lower = Set.new
  seen = Set.new
  "#{post.title} #{sanitizer.sanitize(post.story_text.to_s)}".scan(/[[:alpha:]]+/).each do |word|
    name = PlaceMatcher.normalize(word)
    next unless names.key?(name)
    seen << name
    seen_lower << name if word.match?(/\A[[:lower:]]+\z/)
  end
  seen_lower.each { lower[it] += 1 }
  seen.each { any[it] += 1 }
end

common = names.filter_map do |name, (_, town)|
  name if words.include?(name) || people.include?(name) || lower[name] >= LOWERCASE_POSTS ||
          (town.zero? && any[name] >= VILLAGE_POSTS)
end.sort
path = Rails.root.join("config/gazetteer/common_words.txt")
File.write(path, "# Generated by script/common_place_words.rb; do not edit by hand.\n" + common.join("\n") + "\n")
puts "#{path}: #{common.size} words"
